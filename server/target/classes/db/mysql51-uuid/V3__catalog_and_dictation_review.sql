CREATE TABLE vocabulary_collection (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 title VARCHAR(100) NOT NULL,
 revision INT NOT NULL DEFAULT 1,
 deleted BOOLEAN NOT NULL DEFAULT FALSE,
 request_key VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_catalog_request(owner_id,request_key),
 KEY ix_catalog_owner(owner_id,deleted),
 FOREIGN KEY(owner_id) REFERENCES parent_account(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
CREATE TABLE vocabulary_entry (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 collection_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 grade INT NOT NULL,
 semester VARCHAR(2) NOT NULL,
 unit_name VARCHAR(40) NOT NULL,
 english VARCHAR(100) NOT NULL,
 chinese VARCHAR(300) NOT NULL,
 phonetic VARCHAR(200) NOT NULL DEFAULT '',
 ordinal INT NOT NULL,
 word_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 UNIQUE KEY uk_catalog_word(collection_id,grade,semester,unit_name,word_hash),
 KEY ix_catalog_filter(collection_id,grade,semester,unit_name),
 FOREIGN KEY(collection_id) REFERENCES vocabulary_collection(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
CREATE TABLE dictation_review (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 practice_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 child_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_json MEDIUMTEXT NOT NULL,
 marks_json MEDIUMTEXT NULL,
 elapsed_seconds INT NOT NULL DEFAULT 0,
 total_count INT NOT NULL DEFAULT 0,
 correct_count INT NULL,
 score DECIMAL(5,1) NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 graded_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_review_practice(practice_id),
 KEY ix_review_child(owner_id,child_id),
 FOREIGN KEY(practice_id) REFERENCES practice_session(id),
 FOREIGN KEY(owner_id) REFERENCES parent_account(id),
 FOREIGN KEY(child_id) REFERENCES child_profile(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
CREATE TABLE wrong_word (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 child_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 word_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 english VARCHAR(100) NOT NULL,
 chinese VARCHAR(300) NOT NULL,
 phonetic VARCHAR(200) NOT NULL DEFAULT '',
 grade INT NOT NULL DEFAULT 0,
 semester VARCHAR(2) NOT NULL DEFAULT '',
 unit_name VARCHAR(40) NOT NULL DEFAULT '',
 mistake_count INT NOT NULL DEFAULT 1,
 mastered BOOLEAN NOT NULL DEFAULT FALSE,
 last_practice_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 last_wrong_at DATETIME NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_wrong_word(owner_id,child_id,word_hash),
 KEY ix_wrong_child(owner_id,child_id,mastered),
 FOREIGN KEY(owner_id) REFERENCES parent_account(id),
 FOREIGN KEY(child_id) REFERENCES child_profile(id),
 FOREIGN KEY(last_practice_id) REFERENCES practice_session(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
